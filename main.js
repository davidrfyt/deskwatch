// English is the HTML's original content: capture it on load so we can switch back.
const EN = { ...EN_EXTRA };
const nodes = {
  text: [...document.querySelectorAll('[data-i18n]')],
  html: [...document.querySelectorAll('[data-i18n-html]')],
  alt: [...document.querySelectorAll('[data-i18n-alt]')],
  label: [...document.querySelectorAll('[data-i18n-label]')],
};
nodes.text.forEach((el) => (EN[el.dataset.i18n] = el.textContent));
nodes.html.forEach((el) => (EN[el.dataset.i18nHtml] = el.innerHTML));
nodes.alt.forEach((el) => (EN[el.dataset.i18nAlt] = el.alt));
nodes.label.forEach((el) => (EN[el.dataset.i18nLabel] = el.getAttribute('aria-label')));
EN.title = document.title;
const metaDesc = document.querySelector('meta[name="description"]');
EN.description = metaDesc.content;

let dict = EN;
const galImg = document.getElementById('galImg');
const tabs = [...document.querySelectorAll('.gal-tabs [role="tab"]')];

function setLang(lang) {
  dict = lang === 'es' ? ES : EN;
  nodes.text.forEach((el) => dict[el.dataset.i18n] != null && (el.textContent = dict[el.dataset.i18n]));
  nodes.html.forEach((el) => dict[el.dataset.i18nHtml] != null && (el.innerHTML = dict[el.dataset.i18nHtml]));
  nodes.alt.forEach((el) => dict[el.dataset.i18nAlt] != null && (el.alt = dict[el.dataset.i18nAlt]));
  nodes.label.forEach((el) => dict[el.dataset.i18nLabel] != null && el.setAttribute('aria-label', dict[el.dataset.i18nLabel]));
  document.title = dict.title;
  metaDesc.content = dict.description;
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang button').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  const current = tabs.find((t) => t.getAttribute('aria-selected') === 'true');
  if (current) galImg.alt = dict[current.dataset.alt] || '';
  try {
    localStorage.setItem('deskwatch.lang', lang);
  } catch {}
}

// English by default; Spanish only if the visitor chose it before.
let saved = null;
try {
  saved = localStorage.getItem('deskwatch.lang');
} catch {}
setLang(saved === 'es' ? 'es' : 'en');
document.querySelectorAll('.lang button').forEach((b) => b.addEventListener('click', () => setLang(b.dataset.lang)));

// Nav background once you scroll
const nav = document.getElementById('nav');
const onScroll = () => nav.classList.toggle('scrolled', window.scrollY > 8);
onScroll();
window.addEventListener('scroll', onScroll, { passive: true });

// Gallery tabs (arrow keys move between them)
function selectTab(tab, focus = false) {
  tabs.forEach((t) => {
    const on = t === tab;
    t.setAttribute('aria-selected', String(on));
    t.tabIndex = on ? 0 : -1;
  });
  if (focus) tab.focus();
  if (galImg.getAttribute('src') === tab.dataset.src) return;
  galImg.classList.add('fading');
  const next = new Image();
  next.src = tab.dataset.src;
  next.decode().catch(() => {}).finally(() => {
    galImg.src = tab.dataset.src;
    galImg.alt = dict[tab.dataset.alt] || '';
    galImg.classList.remove('fading');
  });
}
tabs.forEach((t, i) => {
  t.addEventListener('click', () => selectTab(t));
  t.addEventListener('keydown', (e) => {
    const d = e.key === 'ArrowRight' ? 1 : e.key === 'ArrowLeft' ? -1 : 0;
    if (!d) return;
    e.preventDefault();
    selectTab(tabs[(i + d + tabs.length) % tabs.length], true);
  });
});
if (tabs[0]) galImg.alt = dict[tabs[0].dataset.alt] || '';

// Lightbox
const box = document.getElementById('lightbox');
const open = (img) => {
  box.querySelector('img').src = img.currentSrc || img.src;
  box.querySelector('img').alt = img.alt;
  box.showModal();
};
document.querySelector('.zoom')?.addEventListener('click', () => open(galImg));
document.querySelectorAll('.hero-shot img, .tile > img').forEach((img) => {
  img.style.cursor = 'zoom-in';
  img.addEventListener('click', () => open(img));
});
box.addEventListener('click', () => box.close());

// Spotlight that follows the pointer on feature tiles
document.querySelectorAll('.tile').forEach((t) =>
  t.addEventListener('pointermove', (e) => {
    const r = t.getBoundingClientRect();
    t.style.setProperty('--mx', `${e.clientX - r.left}px`);
    t.style.setProperty('--my', `${e.clientY - r.top}px`);
  }),
);

// Reveal on scroll
const io = new IntersectionObserver(
  (entries) =>
    entries.forEach((e) => {
      if (!e.isIntersecting) return;
      e.target.classList.add('in');
      io.unobserve(e.target);
    }),
  { threshold: 0.12, rootMargin: '0px 0px -40px 0px' },
);
document.querySelectorAll('.reveal').forEach((el) => io.observe(el));
